    /// <summary>
    ///     Writes one statement whose middle is a fragment of the <c>.vxml</c>, under a
    ///     <c>#line</c> that points at exactly that fragment.
    /// </summary>
    /// <remarks>
    ///     The offset in the directive is the number of generated characters before the fragment
    ///     starts, which is what makes the mapping land on the fragment rather than on the start of
    ///     the line — the whole reason for the span form.
    /// </remarks>
    void Mapped(BoundExpression expression, string prefix, string suffix) =>
        MappedText(expression.Position, prefix, expression.Text, suffix);

    /// <summary>
    ///     The same, for generated text that is <i>about</i> a fragment of the <c>.vxml</c> without
    ///     being it.
    /// </summary>
    /// <remarks>
    ///     ⚠ <b>One caller, and it is the right-hand side of a <c>ref</c>.</b> A failed conversion is
    ///     reported by Roslyn at the value rather than at the target, so a <c>ref</c> whose member is
    ///     of the wrong type would squiggle <c>n3</c> — a name the author has never seen. Mapping that
    ///     name to the member's own span puts the error where the mistake is.
    /// </remarks>
    void MappedText(LinePositionSpan position, string prefix, string text, string suffix) {
        var indent = new string(' ', depth * 4);
        Directive(position, indent.Length + prefix.Length);
        builder.Append(indent).Append(prefix).Append(text).Append(suffix).Append('\n');
        Line("#line default");
    }

    /// <summary>
    ///     The same, for a value made of several parts — <c>class="btn @kind"</c>, which is one
    ///     interpolated string with one mapped fragment per expression in it.
    /// </summary>
    void Mapped2(ImmutableArray<BoundValuePart> parts, string prefix, string suffix) {
        if (parts is [BoundExpressionPart single]) {
            Mapped(single.Expression, prefix, suffix);
            return;
        }

        Line($"{prefix}string.Concat(");
        depth++;

        for (var i = 0; i < parts.Length; i++) {
            var separator = i == parts.Length - 1 ? string.Empty : ",";

            switch (parts[i]) {
                case BoundLiteralPart literal:
                    Line($"{Quote(literal.Text)}{separator}");
                    break;
                case BoundExpressionPart part:
                    Mapped(part.Expression, string.Empty, separator);
                    break;
                default:
                    break;
            }
        }

        depth--;
        Line($"){suffix}");
    }

    void Directive(LinePositionSpan position, int offset) {
        var start = position.Start;
        var end = position.End;

        builder.Append("#line (")
            .Append(start.Line + 1)
            .Append(',')
            .Append(start.Character + 1)
            .Append(")-(")
            .Append(end.Line + 1)
            .Append(',')
            .Append(end.Character + 1)
            .Append(") ")
            .Append(offset)
            .Append(' ')
            .Append(Quote(filePath))
            .Append('\n');
    }

    /// <summary>Removes the trailing comma from the last written line.</summary>
    /// <remarks>
    ///     A switch expression's final arm takes no comma. Writing arms without one and adding it
    ///     before the next would mean every arm knowing whether it is last, across three different
    ///     emit paths; taking it off once here is the same result with one place to be wrong.
    /// </remarks>
    void Trim() {
        while (builder.Length > 0 && builder[^1] is '\n' or '\r') {
            builder.Length--;
        }

        if (builder.Length > 0 && builder[^1] == ',') {
            builder.Length--;
        }

        builder.Append('\n');
    }

    void Indented(Action write) {
        depth++;
        write();
        depth--;
    }

    void Line(string text = "") {
        if (text.Length > 0) {
            builder.Append(' ', depth * 4);
        }

        builder.Append(text).Append('\n');
    }

    static string Quote(string text) {
        var quoted = new StringBuilder(text.Length + 2).Append('"');

        foreach (var c in text) {
            _ = c switch {
                '"' => quoted.Append("\\\""),
                '\\' => quoted.Append("\\\\"),
                '\r' => quoted.Append("\\r"),
                '\n' => quoted.Append("\\n"),
                '\t' => quoted.Append("\\t"),
                _ => quoted.Append(c)
            };
        }

        return quoted.Append('"').ToString();
    }
