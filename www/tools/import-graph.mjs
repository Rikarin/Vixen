/**
 * Turns `artifacts/docs` — what `nuke Docs` emits — into what the app imports.
 *
 * The .NET side owns the content and this owns nothing: it copies the JSON in, and writes the two
 * TypeScript files that make it reachable from Angular — a manifest the router prerenders from, and
 * a loader map that code-splits the page data per namespace.
 *
 * ⚠ Per namespace, not per type. Measured in docs/plan/spikes/docs-graph: per type the median chunk
 * is 428 bytes, so 3 679 chunks would cost more in build outputs and manifest entries than the
 * content they carry. Per namespace it is 285 chunks at a 3 kB median.
 *
 * Run with `pnpm generate`.
 */
import { cpSync, existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { basename, dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '..', '..');
const source = join(root, 'artifacts', 'docs');
const target = join(here, '..', 'src', 'generated');

if (!existsSync(join(source, 'graph.json'))) {
  console.error(
    `error: ${source}/graph.json is not there.\n` +
      'Run `./build.sh Docs` first — the site renders what the generator emits and has no data of its own.'
  );

  process.exit(1);
}

rmSync(target, { recursive: true, force: true });
mkdirSync(target, { recursive: true });

cpSync(join(source, 'graph.json'), join(target, 'graph.json'));
cpSync(join(source, 'pages'), join(target, 'pages'), { recursive: true });

const hasGuide = existsSync(join(source, 'guide'));

if (hasGuide) {
  cpSync(join(source, 'guide'), join(target, 'guide'), { recursive: true });
}

const pages = readdirSync(join(target, 'pages')).filter(name => name.endsWith('.json'));
const guides = hasGuide
  ? readdirSync(join(target, 'guide')).filter(name => name.endsWith('.json') && name !== 'index.json')
  : [];

const identifier = name => 'chunk_' + name.replace(/[^a-zA-Z0-9]/g, '_');

writeFileSync(
  join(target, 'loaders.ts'),
  `// Generated by tools/import-graph.mjs. Do not edit.\n` +
    `import type { DocNode } from '../app/core/model';\n` +
    `import type { GuidePage } from '../app/core/model';\n\n` +
    `/** One entry per namespace chunk — the unit a route loads. */\n` +
    `export const PAGE_LOADERS: Record<string, () => Promise<DocNode[]>> = {\n` +
    pages
      .map(file => {
        const key = basename(file, '.json');

        // Through `unknown`: TypeScript reads the JSON's classified runs as `string[][]` and the
        // model declares the tuple they are, which is a narrowing a direct cast will not make.
        return `  ${JSON.stringify(key)}: () => import('./pages/${file}').then(m => m.default as unknown as DocNode[])`;
      })
      .join(',\n') +
    `\n};\n\n` +
    `/** One entry per guide page. */\n` +
    `export const GUIDE_LOADERS: Record<string, () => Promise<GuidePage>> = {\n` +
    guides
      .map(file => {
        const key = basename(file, '.json');

        return `  ${JSON.stringify(key)}: () => import('./guide/${file}').then(m => m.default as unknown as GuidePage)`;
      })
      .join(',\n') +
    `\n};\n`
);

const graph = JSON.parse(readFileSync(join(target, 'graph.json'), 'utf8'));
const guideIndex = hasGuide && existsSync(join(target, 'guide', 'index.json'))
  ? JSON.parse(readFileSync(join(target, 'guide', 'index.json'), 'utf8'))
  : [];

// ⚠ Two files, because they are needed at different times and only one of them ships to a browser.
//
// `manifest.ts` is what the nav, the header and the taxonomy counts read: namespaces, guide pages
// and one number per kind. Fifty kilobytes, eagerly loaded, and that is the whole eager cost.
//
// `nodes.ts` is every node. The *server* imports it to know what to prerender, and a list page
// imports it lazily when a reader opens one — so 3 679 entries never enter the initial bundle. With
// them there it was 1.9 MB of JavaScript before a reader had asked for anything.
const nodes = graph.Nodes.map(node => ({
  id: node.Id,
  kind: node.Kind,
  name: node.Name,
  qualifiedName: node.QualifiedName,
  namespace: node.Namespace,
  area: node.Area,
  slug: node.Slug,
  usedBy: node.UsedByCount ?? 0,
  docs: node.Docs ? 1 : 0
}));

const counts = {};

for (const node of nodes) {
  counts[node.kind] = (counts[node.kind] ?? 0) + 1;
}

writeFileSync(
  join(target, 'manifest.ts'),
  `// Generated by tools/import-graph.mjs. Do not edit.\n` +
    `import type { GraphIndex, GuideSummary } from '../app/core/model';\n\n` +
    `export const GRAPH: GraphIndex = ${JSON.stringify({
      solution: graph.Solution,
      configuration: graph.Configuration,
      commit: graph.Commit ?? null,
      projects: graph.ProjectCount,
      total: nodes.length,
      counts,
      namespaces: graph.Namespaces.map(entry => ({
        name: entry.Name,
        slug: entry.Slug,
        areas: entry.Areas,
        count: entry.Count
      }))
    })};\n\n` +
    `export const GUIDE: GuideSummary[] = ${JSON.stringify(
      guideIndex.map(entry => ({
        title: entry.Title,
        slug: entry.Slug,
        kind: entry.Kind,
        area: entry.Area,
        summary: entry.Summary,
        tags: entry.Tags ?? [],
        status: entry.Status,
        symbols: entry.Symbols
      }))
    )};\n`
);

writeFileSync(
  join(target, 'nodes.ts'),
  `// Generated by tools/import-graph.mjs. Do not edit.\n` +
    `import type { NodeSummary } from '../app/core/model';\n\n` +
    `export const NODES: NodeSummary[] = ${JSON.stringify(nodes)};\n`
);

// ── Releases — § 6 ────────────────────────────────────────────────────────────────────────────
//
// Copied rather than recomputed. The tables are committed under docs/api-history/ at the release and
// the generator only ever hands them through, so a rebuilt page cannot disagree with the release note
// that was published — which is the whole reason the store is committed in the first place.
const releaseSource = join(source, 'releases');
const releases = existsSync(join(releaseSource, 'index.json'))
  ? JSON.parse(readFileSync(join(releaseSource, 'index.json'), 'utf8'))
  : [];

if (releases.length > 0) {
  cpSync(releaseSource, join(target, 'releases'), { recursive: true });
}

writeFileSync(
  join(target, 'releases.ts'),
  `// Generated by tools/import-graph.mjs. Do not edit.\n` +
    `import type { ReleaseDetail, ReleaseSummary } from '../app/core/model';\n\n` +
    `/** Newest last, as the store orders them. */\n` +
    `export const RELEASES: ReleaseSummary[] = ${JSON.stringify(releases)};\n\n` +
    `export const RELEASE_LOADERS: Record<string, () => Promise<ReleaseDetail>> = {\n` +
    releases
      .filter(release => release.HasTable)
      .map(
        release =>
          `  ${JSON.stringify(release.Version)}: () => import('./releases/${release.Version}.json')` +
          `.then(m => m.default as unknown as ReleaseDetail)`
      )
      .join(',\n') +
    `\n};\n`
);

const bytes = value => `${(value / 1024 / 1024).toFixed(2)} MB`;
const size = readdirSync(join(target, 'pages'))
  .map(file => readFileSync(join(target, 'pages', file)).length)
  .reduce((total, value) => total + value, 0);

console.log(
  `${graph.Nodes.length} nodes in ${pages.length} chunks (${bytes(size)}), ` +
    `${guides.length} guide pages, ${releases.length} releases, ` +
    `from ${graph.Configuration} at ${graph.Commit?.slice(0, 8) ?? 'no commit'}`
);
